#!/usr/bin/env bash
# Deploy your own Vaka instance on Fly.io: a public server app plus a private ClickHouse app.
#
#   cp deploy/fly/fly.env.example deploy/fly/fly.env   # set VAKA_FLY_APP and VAKA_ADMIN_EMAIL
#   deploy/fly/fly.sh launch       # first time: apps, volumes, secrets, deploy
#   deploy/fly/fly.sh deploy       # later: redeploy both apps (or: deploy server | clickhouse)
#   deploy/fly/fly.sh render       # only write the fly.toml files
#   deploy/fly/fly.sh config       # print the resolved settings
#
# fly.toml has no variable interpolation, so the configs are generated from the *.fly.toml.tmpl
# templates into fly.toml (server) and deploy/fly/clickhouse/fly.toml. Both are git-ignored.
# Settings come from the environment, then deploy/fly/fly.env (or the file in $VAKA_FLY_ENV).
set -euo pipefail

case "${1:-}" in
  render | config | launch | deploy) ;;
  *) sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'; exit 2 ;;
esac

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
cd "$ROOT"

env_file=${VAKA_FLY_ENV:-deploy/fly/fly.env}
if [[ -f $env_file ]]; then
  # Values already in the environment win over the file.
  while IFS= read -r line || [[ -n $line ]]; do
    [[ $line =~ ^[[:space:]]*([A-Z_][A-Z0-9_]*)=(.*)$ ]] || continue
    name=${BASH_REMATCH[1]} value=${BASH_REMATCH[2]}
    value=${value%\"}; value=${value#\"}; value=${value%\'}; value=${value#\'}
    [[ -n ${!name+x} ]] || export "$name=$value"
  done <"$env_file"
fi

: "${VAKA_FLY_APP:?set VAKA_FLY_APP (your server app name) in $env_file or the environment}"
: "${VAKA_FLY_CLICKHOUSE_APP:=${VAKA_FLY_APP}-clickhouse}"
: "${VAKA_FLY_REGION:=arn}"
: "${VAKA_PUBLIC_URL:=https://${VAKA_FLY_APP}.fly.dev}"
: "${VAKA_FLY_VM_SIZE:=shared-cpu-1x}"
: "${VAKA_FLY_VM_MEMORY:=512mb}"
: "${VAKA_FLY_VOLUME_GB:=3}"
: "${VAKA_FLY_CLICKHOUSE_VM_SIZE:=shared-cpu-2x}"
: "${VAKA_FLY_CLICKHOUSE_VM_MEMORY:=2gb}"
: "${VAKA_FLY_CLICKHOUSE_VOLUME_GB:=10}"
VAKA_PUBLIC_URL=${VAKA_PUBLIC_URL%/}

VARS=(VAKA_FLY_APP VAKA_FLY_CLICKHOUSE_APP VAKA_FLY_REGION VAKA_PUBLIC_URL VAKA_FLY_VM_SIZE
  VAKA_FLY_VM_MEMORY VAKA_FLY_CLICKHOUSE_VM_SIZE VAKA_FLY_CLICKHOUSE_VM_MEMORY VAKA_FLY_CLICKHOUSE_VOLUME_GB)

SERVER_TOML=fly.toml
CLICKHOUSE_TOML=deploy/fly/clickhouse/fly.toml

render_one() { # template output
  local content name
  content=$(<"$1")
  for name in "${VARS[@]}"; do
    content=${content//"\${$name}"/${!name}}
  done
  if [[ $content =~ \$\{[A-Z_]+\} ]]; then
    echo "fly.sh: unresolved placeholder ${BASH_REMATCH[0]} in $1" >&2
    exit 1
  fi
  printf '# Generated by deploy/fly/fly.sh from %s. Do not edit.\n%s\n' "$1" "$content" >"$2"
}

render() {
  render_one deploy/fly/vaka.fly.toml.tmpl "$SERVER_TOML"
  render_one deploy/fly/clickhouse/fly.toml.tmpl "$CLICKHOUSE_TOML"
  echo "Wrote $SERVER_TOML ($VAKA_FLY_APP) and $CLICKHOUSE_TOML ($VAKA_FLY_CLICKHOUSE_APP)"
}

config() {
  local name
  for name in "${VARS[@]}" VAKA_FLY_VOLUME_GB VAKA_FLY_ORG VAKA_FLY_IMAGE; do
    printf '%-32s %s\n' "$name" "${!name:-}"
  done
}

fly_cmd() {
  if command -v fly >/dev/null; then fly "$@"; else flyctl "$@"; fi
}

deploy_server() {
  local args=(deploy -c "$SERVER_TOML" --ha=false)
  [[ -n ${VAKA_FLY_IMAGE:-} ]] && args+=(--image "$VAKA_FLY_IMAGE")
  fly_cmd "${args[@]}"
}

deploy_clickhouse() {
  fly_cmd deploy -c "$CLICKHOUSE_TOML" --ha=false
}

app_exists() { fly_cmd apps list --json | grep -q "\"$1\""; }
volume_exists() { fly_cmd volumes list -a "$1" --json | grep -Eqi "\"name\": *\"$2\""; }
secret_exists() { fly_cmd secrets list -a "$1" --json | grep -q "\"$2\""; }

launch() {
  render
  local app org=()
  [[ -n ${VAKA_FLY_ORG:-} ]] && org=(--org "$VAKA_FLY_ORG")
  for app in "$VAKA_FLY_APP" "$VAKA_FLY_CLICKHOUSE_APP"; do
    if app_exists "$app"; then echo "App $app exists"; else fly_cmd apps create "$app" "${org[@]}"; fi
  done
  volume_exists "$VAKA_FLY_APP" vaka_data ||
    fly_cmd volumes create vaka_data -a "$VAKA_FLY_APP" -r "$VAKA_FLY_REGION" -s "$VAKA_FLY_VOLUME_GB" -y
  volume_exists "$VAKA_FLY_CLICKHOUSE_APP" clickhouse_data ||
    fly_cmd volumes create clickhouse_data -a "$VAKA_FLY_CLICKHOUSE_APP" -r "$VAKA_FLY_REGION" \
      -s "$VAKA_FLY_CLICKHOUSE_VOLUME_GB" -y

  local have_ch have_server
  secret_exists "$VAKA_FLY_CLICKHOUSE_APP" CLICKHOUSE_PASSWORD && have_ch=1 || have_ch=0
  secret_exists "$VAKA_FLY_APP" VAKA_CLICKHOUSE_PASSWORD && have_server=1 || have_server=0
  if ((have_ch == 0 && have_server == 0)); then
    local pw
    pw=$(openssl rand -hex 24)
    fly_cmd secrets set -a "$VAKA_FLY_CLICKHOUSE_APP" --stage "CLICKHOUSE_PASSWORD=$pw"
    fly_cmd secrets set -a "$VAKA_FLY_APP" --stage "VAKA_CLICKHOUSE_PASSWORD=$pw"
  elif ((have_ch != have_server)); then
    echo "fly.sh: only one app has the ClickHouse password; set CLICKHOUSE_PASSWORD on $VAKA_FLY_CLICKHOUSE_APP" >&2
    echo "        and VAKA_CLICKHOUSE_PASSWORD on $VAKA_FLY_APP to the same value, then rerun." >&2
    exit 1
  fi
  if ! secret_exists "$VAKA_FLY_APP" VAKA_ADMIN_EMAIL; then
    : "${VAKA_ADMIN_EMAIL:?set VAKA_ADMIN_EMAIL for the first owner account}"
    local generated=
    if [[ -z ${VAKA_ADMIN_PASSWORD:-} ]]; then
      VAKA_ADMIN_PASSWORD=$(openssl rand -base64 18)
      generated=1
    fi
    fly_cmd secrets set -a "$VAKA_FLY_APP" --stage "VAKA_ADMIN_EMAIL=$VAKA_ADMIN_EMAIL" \
      "VAKA_ADMIN_PASSWORD=$VAKA_ADMIN_PASSWORD"
    [[ -n $generated ]] && echo "Admin login: $VAKA_ADMIN_EMAIL / $VAKA_ADMIN_PASSWORD (save it now)"
  fi

  deploy_clickhouse
  deploy_server
  echo "Vaka is up at $VAKA_PUBLIC_URL/ui"
}

case "${1:-}" in
  render) render ;;
  config) config ;;
  launch) launch ;;
  deploy)
    render
    case "${2:-all}" in
      all) deploy_clickhouse && deploy_server ;;
      server) deploy_server ;;
      clickhouse) deploy_clickhouse ;;
      *) echo "usage: $0 deploy [all|server|clickhouse]" >&2; exit 2 ;;
    esac
    ;;
esac
