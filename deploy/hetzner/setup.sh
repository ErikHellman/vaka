#!/usr/bin/env bash
# Prepares a fresh Ubuntu 24.04 VM (made for a Hetzner CX23: 2 vCPU, 4 GB RAM, 40 GB disk) for Vaka:
# admin user with your SSH keys, key-only SSH without root login, firewall, swap, automatic security
# updates, Docker, and a checkout of the repository with a generated .env.
#
# Run as root on the new server:
#   curl -fsSLO https://raw.githubusercontent.com/ErikHellman/vaka/main/deploy/hetzner/setup.sh
#   VAKA_USER=erik VAKA_DOMAIN=vaka.example.com VAKA_ADMIN_EMAIL=you@example.com bash setup.sh
#
# Before closing the root session, check that `ssh $VAKA_USER@<server>` works from a new terminal.
# Safe to re-run: existing users, swap and .env are left alone.
set -euo pipefail

VAKA_USER=${VAKA_USER:-vaka}
VAKA_DIR=${VAKA_DIR:-/opt/vaka}
VAKA_DOMAIN=${VAKA_DOMAIN:-}
VAKA_ADMIN_EMAIL=${VAKA_ADMIN_EMAIL:-}
VAKA_VERSION=${VAKA_VERSION:-0.4.0}
SWAP_GB=${SWAP_GB:-2}

[ "$(id -u)" = 0 ] || { echo "setup.sh: run as root" >&2; exit 1; }
[ -s /root/.ssh/authorized_keys ] || { echo "setup.sh: /root/.ssh/authorized_keys is empty; add your SSH key first" >&2; exit 1; }
. /etc/os-release
[ "$ID" = ubuntu ] || echo "setup.sh: written for Ubuntu 24.04, found $PRETTY_NAME; continuing" >&2

step() { printf '\n==> %s\n' "$*"; }
export DEBIAN_FRONTEND=noninteractive

step "Updating packages"
apt-get update -q
apt-get -yq -o Dpkg::Options::=--force-confold upgrade
apt-get install -yq ca-certificates curl git jq openssl sqlite3 ufw unattended-upgrades

step "Automatic security updates"
cat > /etc/apt/apt.conf.d/20auto-upgrades <<'CONF'
APT::Periodic::Update-Package-Lists "1";
APT::Periodic::Unattended-Upgrade "1";
CONF

step "Admin user $VAKA_USER"
if ! id "$VAKA_USER" >/dev/null 2>&1; then
  adduser --disabled-password --gecos "" "$VAKA_USER"
fi
usermod -aG sudo "$VAKA_USER"
# Key-only login means the user has no password, so sudo must not ask for one.
echo "$VAKA_USER ALL=(ALL) NOPASSWD:ALL" > "/etc/sudoers.d/90-$VAKA_USER"
chmod 440 "/etc/sudoers.d/90-$VAKA_USER"
install -d -m 700 -o "$VAKA_USER" -g "$VAKA_USER" "/home/$VAKA_USER/.ssh"
touch "/home/$VAKA_USER/.ssh/authorized_keys"
cat /root/.ssh/authorized_keys "/home/$VAKA_USER/.ssh/authorized_keys" | sort -u > /tmp/vaka-keys
install -m 600 -o "$VAKA_USER" -g "$VAKA_USER" /tmp/vaka-keys "/home/$VAKA_USER/.ssh/authorized_keys"
rm -f /tmp/vaka-keys

step "SSH: keys only, no root login"
# sshd uses the first value it reads, so this file must sort before 50-cloud-init.conf.
cat > /etc/ssh/sshd_config.d/00-vaka.conf <<CONF
PermitRootLogin no
PasswordAuthentication no
KbdInteractiveAuthentication no
PubkeyAuthentication yes
AllowUsers $VAKA_USER
MaxAuthTries 3
X11Forwarding no
CONF
sshd -t
systemctl reload ssh 2>/dev/null || systemctl restart ssh

step "Firewall: SSH, HTTP and HTTPS only"
ufw default deny incoming
ufw default allow outgoing
ufw allow 22/tcp
ufw allow 80/tcp
ufw allow 443/tcp
ufw allow 443/udp
ufw --force enable
# Note: ports Docker publishes bypass ufw. The compose setup below only publishes 80/443 (Caddy)
# and binds Vaka's plain HTTP port to 127.0.0.1, so nothing else is reachable.

step "Swap (${SWAP_GB} GB)"
if ! swapon --show | grep -q /swapfile; then
  fallocate -l "${SWAP_GB}G" /swapfile
  chmod 600 /swapfile
  mkswap /swapfile
  swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi
cat > /etc/sysctl.d/90-vaka.conf <<'CONF'
vm.swappiness=10
CONF
sysctl -q --system

step "Docker"
if ! command -v docker >/dev/null; then
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu ${VERSION_CODENAME} stable" \
    > /etc/apt/sources.list.d/docker.list
  apt-get update -q
  apt-get install -yq docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
fi
# Rotate container logs so they can't fill the disk.
cat > /etc/docker/daemon.json <<'CONF'
{ "log-driver": "local", "log-opts": { "max-size": "20m", "max-file": "5" } }
CONF
systemctl restart docker
usermod -aG docker "$VAKA_USER"

step "Vaka checkout in $VAKA_DIR"
if [ ! -d "$VAKA_DIR/.git" ]; then
  git clone -q https://github.com/ErikHellman/vaka "$VAKA_DIR"
fi
chown -R "$VAKA_USER:$VAKA_USER" "$VAKA_DIR"

if [ ! -f "$VAKA_DIR/.env" ]; then
  admin_pw=$(openssl rand -base64 18)
  public_url=${VAKA_DOMAIN:+https://$VAKA_DOMAIN}
  cat > "$VAKA_DIR/.env" <<CONF
# Generated by deploy/hetzner/setup.sh. See .env.example and docs/self-hosting.md for every setting.
COMPOSE_FILE=docker-compose.yml:deploy/hetzner/compose.yml
COMPOSE_PROFILES=caddy
VAKA_DOMAIN=${VAKA_DOMAIN:-vaka.example.com}
VAKA_PUBLIC_URL=${public_url:-https://vaka.example.com}
VAKA_PORT=127.0.0.1:8080
VAKA_VERSION=$VAKA_VERSION

VAKA_ADMIN_EMAIL=${VAKA_ADMIN_EMAIL:-admin@example.com}
VAKA_ADMIN_PASSWORD=$admin_pw
# Encrypts stored alert secrets. Moving an existing instance? Replace with that instance's key.
VAKA_SECRET_KEY=$(openssl rand -hex 32)
CLICKHOUSE_PASSWORD=$(openssl rand -hex 24)

# 40 GB disk: keep raw events 90 days by default (per project in the admin UI). Lower it if
# 'df -h /' climbs past ~70%.
VAKA_DEFAULT_RETENTION_DAYS=90
CONF
  chown "$VAKA_USER:$VAKA_USER" "$VAKA_DIR/.env"
  chmod 600 "$VAKA_DIR/.env"
  echo "Generated $VAKA_DIR/.env (admin password: $admin_pw)"
fi

step "Done"
cat <<MSG
Next, as $VAKA_USER (ssh $VAKA_USER@<server> from a NEW terminal before closing this one):
  cd $VAKA_DIR && nano .env          # check VAKA_DOMAIN, VAKA_PUBLIC_URL, VAKA_ADMIN_EMAIL
  docker compose pull && docker compose up -d
  docker compose ps && curl -s localhost:8080/health
Caddy gets the TLS certificate once VAKA_DOMAIN's DNS points at this server.
Moving from Fly.io: see deploy/hetzner/README.md.
MSG
